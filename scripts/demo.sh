do_world() { tsx scripts/setup-world.ts; }

# ── fence: proved with no LLM, in fresh arguments and in the running machines ─
check_fence() {
  if [ "$CLEARANCE_NO_FENCE" = 1 ]; then
    echo "  warn  skipped: --no-fence means there is nothing to check"
    return 0
  fi
  if [ ! -d "$TOOLS/controller-src" ]; then
    echo "  todo  no controller build yet, so nothing to check"
    return 1
  fi
  local args=(--live)
  [ "$(http_code http://127.0.0.1:7710/health)" = 200 ] || args+=(--no-services)
  local output
  if output="$(scripts/check-fence.sh "${args[@]}" 2>&1)"; then
    echo "  ok    $(printf '%s\n' "$output" | grep -c '^PASS') fence checks passed"
    return 0
  fi
  printf '%s\n' "$output" | grep -E '^(FAIL|bwrap)' | head -n 20 | sed 's/^/  /'
  return 1
}
do_fence() { scripts/check-fence.sh --live 2>&1 | grep -v -e '^PASS' -e '^== '; }

# ── reset: the world back to its starting state ─────────────────────────────
check_reset() { return 1; }
