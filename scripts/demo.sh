check_smoke() { return 1; }
do_smoke() { tsx scripts/smoke-spine.ts; }

wanted() {
  [ -z "$ONLY" ] && return 0
  case ",$ONLY," in
    *",$1,"*) return 0 ;;
    *) return 1 ;;
  esac
}

echo "Clearance demo, in $ROOT"
for step in "${ALL_STEPS[@]}"; do
  wanted "$step" || continue
  echo "== $step"
  if [ "$CHECK" = 1 ]; then
    if [ "$step" = reset ]; then
      echo "  a real run resets the world here"
    elif [ "$step" = placeholder ] || [ "$step" = smoke ]; then
      echo "  a real run does this"
    elif "check_$step"; then
      echo "  done"
    else
      echo "  to do"
      TODO+=("$step")
    fi
    continue
  fi
  if "check_$step"; then
    echo "  done"
    continue
  fi
  if [ "$step" = tools ] || [ "${#BLOCKERS[@]}" -gt 0 ]; then
    printf 'Blocked: %s\n' "${BLOCKERS[@]}" >&2
    exit 1
  fi
  if ! "do_$step"; then
    echo "Step $step failed. Fix what it says and run just demo again: it picks up from here." >&2
    exit 1
  fi
  case "$step" in
    reset | placeholder | smoke) ;;
    *)
      if ! "check_$step"; then
        echo "Step $step ran, but its check still says it is not done. See above." >&2
        exit 1
      fi
      ;;
  esac
done

if [ "$CHECK" = 1 ]; then
  echo
  if [ "${#BLOCKERS[@]}" -gt 0 ]; then
    printf 'Blocked: %s\n' "${BLOCKERS[@]}"
    exit 1
  fi
  command_name="just demo$([ "$NO_AGENTS" = 1 ] && echo " --no-agents")"
  then_what="reset$([ "$NO_AGENTS" = 1 ] && echo ", then run the spine")"
  if [ "${#TODO[@]}" -gt 0 ]; then
    echo "Ready to run. $command_name would do: ${TODO[*]} $then_what"
  else
    echo "Everything is up. $command_name would only reset the world$([ "$NO_AGENTS" = 1 ] && echo " and run the spine")."
  fi
  exit 0
fi

