# ── env ─────────────────────────────────────────────────────────────────────
check_env() {
  node scripts/demo-env.mjs --check || return 1
  if ! (cd "$SWITCH_DIR" && docker compose -f deploy/local/standalone-docker-compose.yml -f deploy/local/standalone-docker-compose.build.yml \
    --profile collab --profile gateway --project-directory . config -q) 2>/dev/null; then
    echo "  docker compose does not accept vendor/switch/.env"
    return 1
  fi
}
do_env() {
  if [ ! -f "$SWITCH_DIR/.env" ]; then
    (cd "$SWITCH_DIR" && just init-env) >/dev/null || return 1
  fi
  node scripts/demo-env.mjs
}

# ── stack: Switch standalone, with Mattermost ───────────────────────────────
stack_owner() {
  docker inspect "$COMPOSE_PROJECT-switch-1" --format '{{index .Config.Labels "com.docker.compose.project.working_dir"}}' 2>/dev/null
}
check_stack() {
  local owner
  owner="$(stack_owner)"
  if [ -n "$owner" ] && [ "$(readlink -f "$owner")" != "$(readlink -f "$SWITCH_DIR")" ]; then
    BLOCKERS+=("the Switch stack on these ports belongs to another checkout, $owner. Run there, or stop it and set COMPOSE_PROJECT_NAME so this checkout gets its own volumes")
    return 1
  fi
  [ "$(http_code http://127.0.0.1:8000/health)" = 200 ] &&
    [ "$(http_code http://127.0.0.1:3000/)" = 200 ] &&
    [ "$(http_code http://127.0.0.1:8065/api/v4/system/ping)" = 200 ]
}
# After a reboot the containers exist but are stopped, because Switch's compose file sets no restart policy. `docker
# start` keeps each one's data and settings, where `up` could replace it. Order matters: the gateway's nginx exits at
# once if it cannot resolve `switch`, so Switch has to answer first.
start_stopped_stack() {
  local service _
  for service in postgres mattermost switch gateway; do
    docker inspect "$COMPOSE_PROJECT-$service-1" >/dev/null 2>&1 || return 1
  done
  echo "  starting the existing Switch containers"
  docker start "$COMPOSE_PROJECT-postgres-1" "$COMPOSE_PROJECT-mattermost-1" "$COMPOSE_PROJECT-switch-1" >/dev/null || return 1
  for _ in $(seq 1 60); do
    [ "$(http_code http://127.0.0.1:8000/health)" = 200 ] && break
    sleep 3
  done
  docker start "$COMPOSE_PROJECT-gateway-1" >/dev/null || return 1
  for _ in $(seq 1 40); do
    check_stack && return 0
    sleep 3
  done
  return 1
}
do_stack() {
  start_stopped_stack && return 0
  echo "  building and starting Switch. The first time takes a while"
  (cd "$SWITCH_DIR" && just standalone-up) || return 1
  local _
  for _ in $(seq 1 120); do
    check_stack && return 0
    sleep 5
  done
  echo "  Switch did not answer within 10 minutes: docker compose logs, in $SWITCH_DIR" >&2
  return 1
}

