/**
 * Title card, numbers slide, end card and the slate for missing footage, as HTML rendered to PNG by the
 * same Chromium that does the capture. The bottom of each stays empty for the caption band.
 */
import { join } from "node:path";
import { launchBrowser } from "./capture.ts";
import { measuredParts, type ResultRow, slideRows } from "./results.ts";

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

const PAGE_STYLE = `
  * { box-sizing: border-box; margin: 0; }
  html, body { width: 1920px; height: 1080px; background: #0f1115; color: #f4f5f7;
    font-family: "Noto Sans", "DejaVu Sans", sans-serif; overflow: hidden; }
  .stage { position: absolute; left: 160px; right: 160px; top: 60px; height: 850px;
    display: flex; flex-direction: column; justify-content: center; gap: 36px; }
  h1 { font-size: 64px; line-height: 1.2; font-weight: 700; }
  h1 .accent { color: #f5b301; }
  .lines { display: flex; flex-direction: column; gap: 16px; font-size: 34px; line-height: 1.35; color: #d8dbe2; }
  .lines code { font-family: "Noto Sans Mono", "DejaVu Sans Mono", monospace; font-size: 30px; color: #f5b301; }
  table { border-collapse: collapse; width: 100%; font-size: 27px; line-height: 1.3; }
  th { text-align: left; font-size: 22px; font-weight: 600; color: #9aa0ac; padding: 0 20px 12px 0; }
  td { padding: 16px 20px 16px 0; border-top: 1px solid #2b2f37; vertical-align: top; }
  td.metric { width: 34%; }
  td.clearance { color: #f5b301; font-weight: 700; }
  td.data { width: 16%; font-size: 21px; color: #9aa0ac; }
  .foot { font-size: 23px; color: #9aa0ac; }
  .numbers { gap: 20px; }
  .numbers h1 { font-size: 46px; }
  .numbers table { font-size: 25px; }
  .numbers td { padding: 10px 18px 10px 0; }
  .numbers td.metric { width: 28%; }
  .numbers td.data { width: 30%; font-size: 20px; }
  .still { display: block; height: 400px; width: auto; align-self: flex-start; border: 1px solid #2b2f37; }
`;

function page(body: string): string {
  return `<!doctype html><html><head><meta charset="utf-8"><style>${PAGE_STYLE}</style></head><body>${body}</body></html>`;
}

/** Text that may be a path or a command goes in code type when wrapped in backticks. */
function inlineMarkup(text: string): string {
  return escapeHtml(text).replace(/`([^`]+)`/g, "<code>$1</code>");
}

/** `image` is a data URI: a card is rendered from a string, with nothing to load a file from. */
export function cardHtml(headline: string, lines: string[] = [], image?: string): string {
  const rows = lines.map((line) => `<div>${inlineMarkup(line)}</div>`).join("");
  return page(
    `<div class="stage"><h1>${inlineMarkup(headline)}</h1>${rows ? `<div class="lines">${rows}</div>` : ""}${image ? `<img class="still" alt="" src="${image}">` : ""}</div>`,
  );
}

/** A cell for the slide: only what has a number. */
function slideCell(cell: string): string {
  return escapeHtml(measuredParts(cell));
}

/** The table says "same" for the row above. Alone on a slide that means nothing, so follow it up. */
function dataOf(rows: ResultRow[], row: ResultRow): string {
  for (let index = rows.indexOf(row); index >= 0; index--) {
    const candidate = rows[index] as ResultRow;
    if (candidate.id === row.id && candidate.data.toLowerCase() !== "same") return candidate.data;
  }
  return row.data;
}

export function numbersHtml(headline: string, rows: ResultRow[], selectors: string[]): string {
  const body = slideRows(rows, selectors)
    .map(
      (row) => `<tr>
        <td class="metric">${slideCell(row.metric)}</td>
        <td>${slideCell(row.baseline)}</td>
        <td class="clearance">${slideCell(row.clearance)}</td>
        <td class="data">${slideCell(dataOf(rows, row))}</td>
      </tr>`,
    )
    .join("");
  return page(`<div class="stage numbers">
    <h1>${inlineMarkup(headline)}</h1>
    <table><thead><tr><th>Metric</th><th>Baseline</th><th>Clearance</th><th>Data</th></tr></thead><tbody>${body}</tbody></table>
    <div class="foot">From RESULTS.md, generated by <code>pnpm eval:report</code>. Experiments with no result yet aren't shown.</div>
  </div>`);
}

export function slateHtml(sceneId: string, hint: string): string {
  return cardHtml(`Footage pending: ${sceneId}`, [`Not recorded yet. \`${hint}\``]);
}

export interface CardToRender {
  id: string;
  html: string;
}

/** Renders cards to PNGs at the output resolution. The browser is closed before this returns. */
export async function renderCards(
  cards: CardToRender[],
  directory: string,
): Promise<Map<string, string>> {
  const files = new Map<string, string>();
  if (cards.length === 0) return files;
  const browser = await launchBrowser();
  try {
    const context = await browser.newContext({
      viewport: { width: 1920, height: 1080 },
      deviceScaleFactor: 1,
    });
    const page = await context.newPage();
    for (const card of cards) {
      await page.setContent(card.html, { waitUntil: "load" });
      await page.evaluate(() => document.fonts.ready);
      // Centred content that's too tall loses its top and bottom with no error anywhere, so this is the only place to see it.
      const overflows = await page.evaluate(() => {
        const stage = document.querySelector(".stage");
        return stage !== null && stage.scrollHeight > stage.clientHeight + 1;
      });
      if (overflows)
        throw new Error(`the ${card.id} card doesn't fit its slide. Shorten what it shows`);
      const file = join(directory, `${card.id}.png`);
      await page.screenshot({ path: file });
      files.set(card.id, file);
    }
  } finally {
    await browser.close();
  }
  return files;
}
