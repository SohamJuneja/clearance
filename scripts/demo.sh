# ── controllers: one per machine, each in the fence ─────────────────────────
# By what the process is, not just its number: after a reboot a pid file can name something else entirely. And its
# token sync has to be running from this checkout, or a rerun from another one leaves the old copy going.
machine_running_fenced() {
  local file pid comm token_file token_pid
  file="data/$(fence_stem "$1").pid"
  [ -f "$file" ] || return 1
  pid="$(cat "$file")"
  comm="$(fence_comm "$pid")"
  if [ "$CLEARANCE_NO_FENCE" = 1 ]; then
    case "$comm" in *node) ;; *) return 1 ;; esac
  else
    case "$comm" in *bwrap) ;; *) return 1 ;; esac
  fi
  fence_cmdline "$pid" | grep -q "cli.mjs run --data-dir $(fence_data_dir "$1") " || return 1
  if [ "$CLEARANCE_NO_FENCE" != 1 ] && fence_has_provider "$1" claude && [ -z "$(env_value ANTHROPIC_API_KEY)" ]; then
    token_file="data/$(fence_stem "$1").token.pid"
    token_pid="$(cat "$token_file" 2>/dev/null)"
    [ -n "$token_pid" ] && fence_cmdline "$token_pid" | grep -q "$ROOT/scripts/fence-claude-token.sh" || return 1
  fi
}
check_controllers() {
  local machine bad=0
  for machine in "${MACHINES[@]}"; do
    if machine_running_fenced "$machine"; then
      echo "  ok    $machine is running$([ "$CLEARANCE_NO_FENCE" = 1 ] && echo ' with NO FENCE' || echo ' in the fence')"
    else
      echo "  todo  $machine is not running as it should be, in the fence and with its token sync from this checkout"
      bad=1
    fi
  done
  return "$bad"
}
do_controllers() {
  local machine _
  for machine in "${MACHINES[@]}"; do
    scripts/setup-controller.sh --machine "$machine" || return 1
  done
  # Agents are only created on a machine that has said what it can run.
  for _ in $(seq 1 30); do
    tsx scripts/demo-status.ts machines >/dev/null && return 0
    sleep 2
  done
  tsx scripts/demo-status.ts machines
}

# ── agents ──────────────────────────────────────────────────────────────────
check_agents() {
  [ -f node_modules/.modules.yaml ] && [ -f .env ] && [ "$(http_code http://127.0.0.1:8000/health)" = 200 ] && tsx scripts/demo-status.ts agents
}
# That line tells someone running the script by hand to restart core. Here the reset at the end of this run does.
do_agents() {
  tsx scripts/setup-agents.ts --source acme-mini-app | grep -v '^hook tokens are in' || return 1
  tsx scripts/setup-baseline.ts
}

# ── services: Acme, gate, core, desk ────────────────────────────────────────
check_services() {
  local service bad=0 line
  for service in acme gate core desk; do
    line="$(scripts/services.sh status "$service" 2>/dev/null)"
    if [ ! -s "data/run/$service.pgid" ]; then
      case "$line" in
        *": up"*) BLOCKERS+=("port for $service answers, but this checkout did not start it. Stop the other one first") ;;
      esac
      echo "  todo  $service was not started from this checkout"
      bad=1
      continue
    fi
    case "$line" in
      *": up"*) echo "  ok    $line" ;;
      *)
        echo "  todo  $line"
        bad=1
        ;;
    esac
  done
  return "$bad"
}
# Restarted, not just started: setup-agents may have written new hook tokens, which core reads when it starts.
do_services() {
  # The Desk serves a build that a fresh clone does not have.
  if [ ! -f packages/desk/dist/index.html ]; then
    pnpm desk:build >/dev/null || return 1
  fi
  scripts/services.sh down gate core >/dev/null
  scripts/services.sh up acme gate core desk
}

