  [ -d "$SWITCH_DIR/.git" ] && [ "$(git -C "$SWITCH_DIR" rev-parse HEAD 2>/dev/null)" = "$SWITCH_SHA" ]
}
do_fetch() { just switch-fetch; }

# ── install ─────────────────────────────────────────────────────────────────
