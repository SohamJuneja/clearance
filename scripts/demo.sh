#!/usr/bin/env bash
# `just demo`: everything a judge needs, from a fresh clone. Safe to rerun: each step checks first and does only
# what is missing. That includes after a reboot, which stops Switch, the controllers and the services: one rerun brings
# them all back. See PLAN 13 section 6.
#
#   just demo                       do it
#   just demo --check               say what is done and what is missing. Changes nothing in the stack
#   just demo --only fetch,env      only these steps
#   just demo --no-agents           no agents, no key, no LLM, no bubblewrap: Switch, personas, services and the Desk, then
#                                   the scripted spine (scripts/smoke-spine.ts) through real cards and real presses
#   just demo --no-fence            real agents with no sandbox, for a host without bubblewrap. It says what that loses
#
# Steps, in order: tools fetch install env stack personas controllers agents services world fence reset
# With --no-agents: tools fetch install env stack personas placeholder services world reset smoke
#
# What it needs from you
#   Docker with compose v2, Node 22 or later, pnpm, just, git, curl. For agents, also rsync and Linux with bubblewrap,
#   unless you pass --no-fence. Never run --no-fence on a machine you care about.
#   Claude Code on the PATH, and one way for it to sign in. Without both this stops at its first step and says so,
#   rather than leave half a demo running:
#     - ANTHROPIC_API_KEY in .env, the simple way. Claude agents can read this key: see docs/threat-model.md.
#     - or a Claude login on this host (`claude login`). Each fenced machine gets a copy of its short-lived access
#       token, never the refresh token. Claude on the host keeps it fresh, with one tiny Claude call if nothing else has.
#   OpenCode's agent uses a free model and needs no key, and this installs OpenCode where the fence can see it. Codex
#   and Cursor agents wait for their logins, and rerunning this creates them once those exist.
#
# Secrets are read and generated by scripts and never printed.
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"
export CLEARANCE_ROOT="$ROOT"
REPO_ROOT="$ROOT"
cd "$ROOT" || exit 1
# shellcheck source=scripts/fence.sh
source "$HERE/fence.sh"

ALL_STEPS=(tools fetch install env stack personas controllers agents services world fence reset)
CHECK=0
ONLY=""
NO_AGENTS=0
export CLEARANCE_NO_FENCE="${CLEARANCE_NO_FENCE:-0}"
while [ $# -gt 0 ]; do
  case "$1" in
    --check)
      CHECK=1
      shift
      ;;
    --only)
      ONLY="$2"
      shift 2
      ;;
    --no-agents)
      NO_AGENTS=1
      shift
      ;;
    --no-fence)
      CLEARANCE_NO_FENCE=1
      shift
      ;;
    *)
      echo "usage: just demo [--check] [--only <step,step>] [--no-agents | --no-fence]" >&2
      echo "steps: ${ALL_STEPS[*]}" >&2
      exit 2
      ;;
  esac
done
if [ "$NO_AGENTS" = 1 ] && [ "$CLEARANCE_NO_FENCE" = 1 ]; then
  echo "--no-agents runs no agents, so there is nothing for --no-fence to do. Pick one." >&2
  exit 2
fi
if [ "$NO_AGENTS" = 1 ]; then
  ALL_STEPS=(tools fetch install env stack personas placeholder services world reset smoke)
elif [ "$CLEARANCE_NO_FENCE" = 1 ]; then
  fence_off_warning
fi

SWITCH_DIR="$ROOT/vendor/switch"
SWITCH_SHA="$(sed -n 's/^switch_sha := "\(.*\)"/\1/p' justfile)"
MACHINES=(clearance-priya clearance-priya-base clearance-alex clearance-alex-open)
COMPOSE_PROJECT="${COMPOSE_PROJECT_NAME:-switch}"
BLOCKERS=()
TODO=()

http_code() { curl -s -m 3 -o /dev/null -w '%{http_code}' "$1" 2>/dev/null; }
tsx() { pnpm exec tsx --env-file=.env "$@"; }
env_value() { sed -n "s/^$1=//p" .env 2>/dev/null | tail -n 1 | sed -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'$/\1/"; }

# ── tools ───────────────────────────────────────────────────────────────────
check_tools() {
  local missing=() tool
  for tool in docker node pnpm just git curl; do
    command -v "$tool" >/dev/null 2>&1 || missing+=("$tool")
  done
  if [ "$NO_AGENTS" != 1 ]; then
    command -v rsync >/dev/null 2>&1 || missing+=(rsync)
  fi
  if [ "${#missing[@]}" -gt 0 ]; then
    BLOCKERS+=("install: ${missing[*]}")
    return 1
  fi
  if ! docker compose version >/dev/null 2>&1; then
    BLOCKERS+=("Docker needs compose v2")
    return 1
  fi
  if [ "$(node -p 'process.versions.node.split(".")[0]')" -lt 22 ]; then
    BLOCKERS+=("Node 22 or later is needed, this is $(node --version)")
    return 1
  fi
  # The scripted spine runs no agent, so it needs neither a fence nor a key.
  if [ "$NO_AGENTS" = 1 ]; then
    echo "  ok    --no-agents needs no key and no bubblewrap"
    return 0
  fi
  if [ "$CLEARANCE_NO_FENCE" = 1 ]; then
    echo "  warn  --no-fence: agents run with no sandbox. See the warning above"
  else
    local why
    if ! why="$(fence_supported 2>&1)"; then
      BLOCKERS+=("the agent fence cannot work here: $why")
      return 1
    fi
  fi
  check_claude
}
# Found out here or not at all: the machines that run Claude agents can't start without it, so going on would build and
# enroll everything else and then stop halfway.
check_claude() {
  local no_agents="To see Clearance with no agents, no key and no LLM: just demo --no-agents"
  if ! command -v claude >/dev/null 2>&1; then
    BLOCKERS+=("Claude Code is not installed, and the agents run on it: npm install -g @anthropic-ai/claude-code. $no_agents")
    return 1
  fi
  if [ -n "$(env_value ANTHROPIC_API_KEY)" ]; then
    echo "  ok    Claude agents will use ANTHROPIC_API_KEY from .env"
    return 0
  fi
  if [ -f "$HOME/.claude/.credentials.json" ]; then
    echo "  ok    Claude agents will use this host's Claude login, without its refresh token"
    return 0
  fi
  # macOS keeps the login in the keychain, with no file to find. A fence can't take a copy of that, but --no-fence uses
  # the real home and needs no copy.
  if [ "$CLEARANCE_NO_FENCE" = 1 ] && claude auth status 2>/dev/null | grep -q '"loggedIn": *true'; then
    echo "  ok    Claude agents will use this host's Claude login"
    return 0
  fi
  BLOCKERS+=("Claude agents have no way to sign in. Put ANTHROPIC_API_KEY in .env, or run claude login, then run just demo again. $no_agents")
  return 1
}
do_tools() { return 1; }

